package store

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"path/filepath"
	"testing"

	"github.com/asdfgh129/ud/internal/core"
)

func batchDigest(b []byte) string {
	sum := sha256.Sum256(b)
	return hex.EncodeToString(sum[:])
}

// ADR-0015 ③ requires chunk completions to be flushed in batches. Atomicity is
// the property that makes batching safe: a batch either lands completely (all
// chunk rows + the accumulated progress delta + the digest rows) or not at all,
// so a crash can only cost a re-download of one flush window, never a task whose
// bytes_done disagrees with its chunk table.
func TestWriteChunkDoneBatchIsAtomic(t *testing.T) {
	st, err := Open(filepath.Join(t.TempDir(), "state.db"), nil)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { st.Close() })
	ctx := context.Background()

	id := mustInsertTask(t, st, core.StateRunning, core.InputURL, "https://x/a")
	res := mustSaveResource(t, st, id, 12)
	if n, err := st.CreateChunks(ctx, id, 0, 12, 4); err != nil || n != 3 {
		t.Fatalf("chunks=%d err=%v", n, err)
	}
	c1, ok, err := st.Next(ctx, id)
	if err != nil || !ok {
		t.Fatalf("claim c1: ok=%v err=%v", ok, err)
	}
	c2, ok, err := st.Next(ctx, id)
	if err != nil || !ok {
		t.Fatalf("claim c2: ok=%v err=%v", ok, err)
	}
	chunks, err := st.Chunks(ctx, id)
	if err != nil {
		t.Fatal(err)
	}
	pending := chunks[2] // deliberately left unclaimed

	// Mixed batch (generated by a caller bug, not by the scheduler) must roll
	// back in full: the assigned chunk must not become done behind our back.
	err = st.WriteChunkDoneBatch(ctx, []ChunkDone{
		{Chunk: c1, ResourceID: res.ID, Digest: batchDigest([]byte("AAAA"))},
		{Chunk: pending, ResourceID: res.ID, Digest: batchDigest([]byte("CCCC"))},
	})
	if err == nil {
		t.Fatal("batch containing a non-assigned chunk must fail")
	}
	task, err := st.GetTask(ctx, id)
	if err != nil {
		t.Fatal(err)
	}
	if task.BytesDone != 0 {
		t.Fatalf("failed batch leaked progress: bytes_done=%d", task.BytesDone)
	}
	after, err := st.Chunks(ctx, id)
	if err != nil {
		t.Fatal(err)
	}
	if after[0].State != core.ChunkAssigned {
		t.Fatalf("failed batch changed chunk state: %s", after[0].State)
	}
	if d, _ := st.ChunkDigest(ctx, res.ID, 0, 0); d != "" {
		t.Fatalf("failed batch wrote a digest row: %q", d)
	}

	// Happy path: two completions in one transaction.
	if err := st.WriteChunkDoneBatch(ctx, []ChunkDone{
		{Chunk: c1, ResourceID: res.ID, Digest: batchDigest([]byte("AAAA"))},
		{Chunk: c2, ResourceID: res.ID, Digest: batchDigest([]byte("BBBB")), MirrorIndex: 1},
	}); err != nil {
		t.Fatal(err)
	}
	task, err = st.GetTask(ctx, id)
	if err != nil {
		t.Fatal(err)
	}
	if task.BytesDone != 8 {
		t.Fatalf("bytes_done=%d want 8 (sum of the batch)", task.BytesDone)
	}
	after, err = st.Chunks(ctx, id)
	if err != nil {
		t.Fatal(err)
	}
	if after[0].State != core.ChunkDone || after[1].State != core.ChunkDone {
		t.Fatalf("states=%s,%s want done,done", after[0].State, after[1].State)
	}
	if after[2].State != core.ChunkPending {
		t.Fatalf("unclaimed chunk changed state: %s", after[2].State)
	}
	if d, _ := st.ChunkDigest(ctx, res.ID, 0, 1); d != batchDigest([]byte("BBBB")) {
		t.Fatalf("digest of second record wrong: %q", d)
	}
}

// A batch spanning two tasks would apply one progress delta to one task and the
// chunk rows of both; the store refuses instead of silently splitting.
func TestWriteChunkDoneBatchRejectsMixedTasks(t *testing.T) {
	st, err := Open(filepath.Join(t.TempDir(), "state.db"), nil)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { st.Close() })
	ctx := context.Background()

	idA := mustInsertTask(t, st, core.StateRunning, core.InputURL, "https://x/a")
	resA := mustSaveResource(t, st, idA, 4)
	if _, err := st.CreateChunks(ctx, idA, 0, 4, 4); err != nil {
		t.Fatal(err)
	}
	idB := mustInsertTask(t, st, core.StateRunning, core.InputURL, "https://x/b")
	resB := mustSaveResource(t, st, idB, 4)
	if _, err := st.CreateChunks(ctx, idB, 0, 4, 4); err != nil {
		t.Fatal(err)
	}
	a, ok, err := st.Next(ctx, idA)
	if err != nil || !ok {
		t.Fatalf("claim a: ok=%v err=%v", ok, err)
	}
	b, ok, err := st.Next(ctx, idB)
	if err != nil || !ok {
		t.Fatalf("claim b: ok=%v err=%v", ok, err)
	}
	err = st.WriteChunkDoneBatch(ctx, []ChunkDone{
		{Chunk: a, ResourceID: resA.ID, Digest: batchDigest([]byte("AAAA"))},
		{Chunk: b, ResourceID: resB.ID, Digest: batchDigest([]byte("BBBB"))},
	})
	if err == nil {
		t.Fatal("batch mixing tasks must be rejected")
	}
	for _, id := range []core.TaskID{idA, idB} {
		task, err := st.GetTask(ctx, id)
		if err != nil {
			t.Fatal(err)
		}
		if task.BytesDone != 0 {
			t.Fatalf("task %s advanced despite rejection: %d", id, task.BytesDone)
		}
	}
}
