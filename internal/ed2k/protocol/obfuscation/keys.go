package obfuscation

import (
	"crypto/md5"
	"encoding/binary"

	"github.com/asdfgh129/ud/internal/ed2k/protocol"
)

// eMule client-to-client obfuscation constants. Values verified against
// aMule EncryptedStreamSocket.cpp and eNode ed2k/tcpcrypt.js (both agree).
const (
	MagicValueRequester        = 34         // 0x22 — modifies requester-send / server-receive key
	MagicValueServer           = 203        // 0xCB — modifies server-send / requester-receive key
	MagicValueSync             = 0x835E6FC4 // sync token carried in the handshake
	EncryptionObfuscation byte = 0          // ENM_OBFUSCATION, the only supported method
	RC4DiscardBytes            = 1024       // first keystream bytes dropped for TCP keys
)

// keyMaterialLen is the 21-byte MD5 input: userHash(16) + magic(1) + randomPart(4).
const keyMaterialLen = 16 + 1 + 4

// deriveKey builds one RC4 direction key from the 21-byte layout and drops
// the first RC4DiscardBytes keystream bytes, matching eMule SetKey().
//
// randomPart is the 4-byte value generated by the initiating client (A) and
// sent in cleartext in the handshake; userHash is the hash of the peer whose
// identity anchors the key (target hash on A, local hash on B).
func deriveKey(userHash protocol.Hash, magic byte, randomPart uint32) *Cipher {
	buf := make([]byte, keyMaterialLen)
	copy(buf[:16], userHash.Bytes())
	buf[16] = magic
	binary.LittleEndian.PutUint32(buf[17:21], randomPart)
	sum := md5.Sum(buf)
	c := NewCipher(sum[:])
	c.Discard(RC4DiscardBytes)
	return c
}

// DeriveDirectionKeys returns the (send, receive) RC4 key pair for one side of
// a client-to-client obfuscated connection.
//
// Initiator A (knows the target's hash):
//
//	send = MD5(targetHash || 0x22 || randomPart)
//	recv = MD5(targetHash || 0xCB || randomPart)
//
// Responder B (uses its own hash and A's received randomPart):
//
//	recv = MD5(localHash  || 0x22 || randomPart)
//	send = MD5(localHash  || 0xCB || randomPart)
//
// A.send pairs with B.recv, and A.recv pairs with B.send.
func DeriveDirectionKeys(userHash protocol.Hash, randomPart uint32, initiator bool) (send, recv *Cipher) {
	if initiator {
		return deriveKey(userHash, MagicValueRequester, randomPart),
			deriveKey(userHash, MagicValueServer, randomPart)
	}
	return deriveKey(userHash, MagicValueServer, randomPart),
		deriveKey(userHash, MagicValueRequester, randomPart)
}
